#!/usr/bin/env python3
"""Trim per-platform LLVM assets and regenerate the host-backend stub file.

Three operations, all idempotent:

1. Backend trim. Each platform keeps only the backend for its own architecture
   plus the lld driver that emits its own object format. The remaining backend
   archives are deleted.

2. Stub generation. lld's in-process driver inlines
   llvm::InitializeAllTargetInfos and friends, so the deleted backends stay
   referenced at link time. targets_host_only.cpp defines an empty initializer
   for every LLVMInitialize* symbol that the retained archives leave undefined.
   The symbol list is computed with llvm-nm, so it stays exact when LLVM or the
   archive set changes.

3. Header dedupe. Headers that are byte-identical across every platform tree are
   moved to the shared llvm/18.1.3/include root; cgo passes both roots on the
   include path. Headers that differ stay per platform.

Run this after regenerating a platform tree, then commit the result.

Usage: scripts/trim_platform_assets.py [--check]
"""
from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
ROOT = REPO_ROOT / "llvm" / "18.1.3"
SHARED_INCLUDE = ROOT / "include"
STUB_FILE = REPO_ROOT / "targets_host_only.cpp"

# Platform -> (host backend, lld drivers that stay, preprocessor guard).
PLATFORMS = {
    "linux-amd64": ("X86", {"ELF", "Common"}, "defined(__linux__) && defined(__x86_64__)"),
    "windows-amd64": ("X86", {"COFF", "MinGW", "Common"}, "defined(_WIN32) && defined(__x86_64__)"),
    "darwin-arm64": ("AArch64", {"MachO", "Common"}, "defined(__APPLE__) && defined(__aarch64__)"),
}

# Targets that a full LLVM build can produce but that Targets.def may omit.
EXTRA_TARGETS = ("M68k", "Xtensa")


def targets_of(tree: Path) -> list[str]:
    defs = tree / "include" / "llvm" / "Config" / "Targets.def"
    targets = re.findall(r"^LLVM_TARGET\((\w+)\)", defs.read_text(), re.M)
    return targets + [t for t in EXTRA_TARGETS if t not in targets]


def plan_backend_trim(platform: str) -> tuple[list[Path], list[Path]]:
    tree = ROOT / platform
    host, keep_lld, _ = PLATFORMS[platform]
    targets = targets_of(tree)
    drop, keep = [], []
    for archive in sorted(tree.joinpath("lib").glob("*.a")):
        target = next((t for t in targets if archive.name.startswith(f"libLLVM{t}")), None)
        if target is not None:
            (keep if target == host else drop).append(archive)
            continue
        match = re.match(r"liblld(\w+)\.a$", archive.name)
        if match is None:
            keep.append(archive)
        elif match.group(1) in keep_lld:
            keep.append(archive)
        else:
            drop.append(archive)
    return drop, keep


def init_symbols(archive: Path, undefined: bool) -> set[str]:
    flag = "-u" if undefined else "--defined-only"
    result = subprocess.run(["llvm-nm", "-g", flag, str(archive)],
                            capture_output=True, text=True)
    if result.returncode:
        raise SystemExit(f"llvm-nm failed on {archive}: {result.stderr.strip()}")
    names = set()
    for line in result.stdout.splitlines():
        fields = line.split()
        if not fields:
            continue
        # Mach-O prefixes C symbols with an underscore.
        name = fields[-1].lstrip("_")
        if name.startswith("LLVMInitialize"):
            names.add(name)
    return names


def plan_stubs(platform: str, keep: list[Path]) -> list[str]:
    defined: set[str] = set()
    undefined: set[str] = set()
    for archive in keep:
        defined |= init_symbols(archive, undefined=False)
        undefined |= init_symbols(archive, undefined=True)
    return sorted(undefined - defined)


def stub_source(stubs: dict[str, list[str]]) -> str:
    lines = [
        "// Stubs for the target backends that this platform's archives do not ship.",
        "//",
        "// Each platform keeps only its own backend: X86 on linux/windows, AArch64 on",
        "// darwin. lld's in-process driver inlines llvm::InitializeAllTargetInfos and",
        "// friends, so every deleted backend stays referenced at link time. The empty",
        "// initializers below satisfy those references and keep the other target",
        "// archives out of the link and out of the module.",
        "//",
        "// Generated by scripts/trim_platform_assets.py from the retained archives;",
        "// do not edit by hand. Code generation, assembly parsing, and the MC layer",
        "// stay real for the host backend only.",
    ]
    total = 0
    for platform, symbols in stubs.items():
        if not symbols:
            continue
        total += len(symbols)
        guard = PLATFORMS[platform][2]
        lines += [
            "",
            f"// {platform}: {len(symbols)} stubs",
            f"#if {guard}",
            'extern "C" {',
        ]
        lines += [f"void {symbol}() {{}}" for symbol in symbols]
        lines += ['} // extern "C"', "#endif"]
    if total == 0:
        lines += ["", "// No stubs needed: every retained tree was built for its host backend only."]
    return "\n".join(lines) + "\n"


def plan_header_dedupe() -> list[tuple[str, bytes]]:
    digests: dict[str, list[str]] = {}
    contents: dict[str, bytes] = {}
    for platform in PLATFORMS:
        base = ROOT / platform / "include"
        if not base.is_dir():
            return []
        for path in base.rglob("*"):
            if not path.is_file():
                continue
            rel = str(path.relative_to(base))
            data = path.read_bytes()
            contents[rel] = data
            digests.setdefault(rel, []).append(hashlib.sha256(data).hexdigest())
    count = len(PLATFORMS)
    return [(rel, contents[rel]) for rel, pool in sorted(digests.items())
            if len(pool) == count and len(set(pool)) == 1]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="report the plan and sizes without touching files")
    args = parser.parse_args()

    if not ROOT.is_dir():
        print(f"missing {ROOT}", file=sys.stderr)
        return 1

    plans = {platform: plan_backend_trim(platform) for platform in PLATFORMS}
    stubs = {platform: plan_stubs(platform, keep) for platform, (_, keep) in plans.items()}
    dedupe = plan_header_dedupe()

    for platform, (drop, _) in plans.items():
        print(f"{platform}: drop {len(drop)} archives, "
              f"{sum(p.stat().st_size for p in drop) / 1048576:.3f} MiB, "
              f"{len(stubs[platform])} stubs")
    print(f"shared headers: {len(dedupe)} files, "
          f"{sum(len(data) for _, data in dedupe) * (len(PLATFORMS) - 1) / 1048576:.3f} MiB saved")

    if args.check:
        return 0

    STUB_FILE.write_text(stub_source(stubs))

    for drop, _ in plans.values():
        for archive in drop:
            archive.unlink()

    for rel, data in dedupe:
        destination = SHARED_INCLUDE / rel
        destination.parent.mkdir(parents=True, exist_ok=True)
        source = next(ROOT / platform / "include" / rel for platform in PLATFORMS
                      if (ROOT / platform / "include" / rel).exists())
        if source != destination:
            shutil.move(str(source), str(destination))
        for platform in PLATFORMS:
            duplicate = ROOT / platform / "include" / rel
            if duplicate.exists() and duplicate != destination:
                duplicate.unlink()

    for platform in PLATFORMS:
        base = ROOT / platform / "include"
        for directory in sorted((p for p in base.rglob("*") if p.is_dir()), reverse=True):
            if not any(directory.iterdir()):
                directory.rmdir()
        if base.is_dir() and not any(base.iterdir()):
            base.rmdir()

    total = sum(p.stat().st_size for p in ROOT.rglob("*") if p.is_file())
    print(f"llvm/18.1.3 tree: {total / 1048576:.3f} MiB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())